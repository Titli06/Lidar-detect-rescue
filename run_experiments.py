"""
run_experiments.py
------------------
End-to-end Phase-1 experiment:

1. Train the learned victim model (Trial C) on degraded TRAIN scenes.
2. Sweep smoke density over held-out TEST scenes; run all three trials.
3. Save a results table (CSV + JSON) and all figures.

Run:  python3 run_experiments.py
"""

import os, sys, json, csv
import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "src"))
from scene import make_scene
from smoke import apply_smoke
from features import compute_features
from trials import trial_a_baseline, trial_b_classical, LearnedVictimModel
from metrics import evaluate, aggregate

RESULTS = os.path.join(os.path.dirname(__file__), "results")
FIG = os.path.join(os.path.dirname(__file__), "figures")
os.makedirs(RESULTS, exist_ok=True)
os.makedirs(FIG, exist_ok=True)

SMOKE_LEVELS = [0.0, 0.3, 0.6, 0.9, 1.2]
N_TRAIN = 14
N_TEST = 12
MASTER_SEED = 42


def train_learned_model():
    print("[1/3] Training learned victim model (Trial C) ...")
    rng = np.random.default_rng(MASTER_SEED)
    feats_list, labels_list = [], []
    for i in range(N_TRAIN):
        pts, lab, meta = make_scene(seed=1000 + i)
        # train across a spread of smoke levels so the model generalises
        a = float(rng.choice([0.3, 0.6, 0.9, 1.2]))
        dp, dl = apply_smoke(pts, lab, a, rng=rng, room=meta["room"])
        feats_list.append(compute_features(dp))
        labels_list.append(dl)
    model = LearnedVictimModel().fit(feats_list, labels_list)
    # quick feature-importance readout for the log
    names = ["range", "height", "density", "knn_mean", "knn_std",
             "planarity", "linearity"]
    imp = model.clf.feature_importances_
    print("      feature importance:",
          ", ".join(f"{n}={v:.2f}" for n, v in zip(names, imp)))
    return model


def run_sweep(model):
    print("[2/3] Running smoke sweep over test scenes ...")
    trials = {"A_baseline": trial_a_baseline,
              "B_classical": trial_b_classical,
              "C_learned": model.predict}
    raw = {t: {a: [] for a in SMOKE_LEVELS} for t in trials}

    for i in range(N_TEST):
        pts, lab, meta = make_scene(seed=2000 + i)
        for a in SMOKE_LEVELS:
            rng = np.random.default_rng(7000 + i * 10 + int(a * 10))
            dp, dl = apply_smoke(pts, lab, a, rng=rng, room=meta["room"])
            for tname, fn in trials.items():
                centroid, mask = fn(dp)
                raw[t := tname][a].append(evaluate(centroid, mask, dl, meta))

    table = {t: {a: aggregate(raw[t][a]) for a in SMOKE_LEVELS} for t in trials}
    return table


def save_table(table):
    with open(os.path.join(RESULTS, "results.json"), "w") as f:
        json.dump(table, f, indent=2)
    rows = []
    for t, per_a in table.items():
        for a, m in per_a.items():
            rows.append({"trial": t, "smoke_alpha": a, **m})
    with open(os.path.join(RESULTS, "results.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader(); w.writerows(rows)
    # pretty print
    print("\n==== RESULTS (averaged over test scenes) ====")
    print(f"{'trial':12} {'alpha':>5} {'detect%':>8} {'hit%':>6} "
          f"{'loc_err_m':>10} {'vic_recall':>11}")
    for t, per_a in table.items():
        for a, m in per_a.items():
            le = f"{m['loc_err']:.3f}" if not np.isnan(m['loc_err']) else "  n/a"
            print(f"{t:12} {a:5.1f} {100*m['detected']:8.0f} {100*m['hit']:6.0f} "
                  f"{le:>10} {m['vic_recall']:11.2f}")


if __name__ == "__main__":
    model = train_learned_model()
    table = run_sweep(model)
    save_table(table)
    # figures are generated by a separate module to keep concerns apart
    import make_figures
    make_figures.main(model)
    print("\n[3/3] Done. See results/ and figures/.")
